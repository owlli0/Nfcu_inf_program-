"""
Назначение программы:
Расчёт необходимого объёма топлива и итоговой стоимости
поездки на автомобиле по заданным параметрам маршрута.
"""

# --- Входные данные ---
# distance: расстояние маршрута в километрах (вещественное или целое число)
# consumption: средний расход топлива в литрах на 100 км (вещественное или целое число)
# price_per_liter: стоимость одного литра топлива в рублях (вещественное или целое число)

distance = float(input("Введите расстояние поездки (км): "))
consumption = float(input("Введите средний расход топлива (л/100 км): "))
price_per_liter = float(input("Введите стоимость 1 литра топлива (руб.): "))

# --- Расчётная часть ---
# Пояснение формулы:
# 1. fuel_needed: чтобы узнать расход на 1 км, делим расход на 100,
#    затем умножаем на пройденное расстояние (S * R / 100).
# 2. total_cost: объём топлива умножается на цену одного литра (V * P).

fuel_needed = (distance * consumption) / 100.0
total_cost = fuel_needed * price_per_liter

# --- Вывод результатов ---
print("\n--- Результаты расчёта ---")
print(f"Дистанция: {distance:.2f} км")
print(f"Необходимый объём топлива: {fuel_needed:.2f} л")
print(f"Общая стоимость поездки: {total_cost:.2f} руб.")
