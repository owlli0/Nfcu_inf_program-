"""
Лабораторная работа: Управляющие конструкции и функции в Python.
Программа состоит из трех частей:
1. Проверка четности числа с разделением на три случая (if/elif/else).
2. Вывод чисел от 1 до N, кратных 3 (цикл for).
3. Функция нахождения максимума из двух чисел max_two(a, b).
"""


# =====================================================================
# Часть 3: Пользовательская функция
# =====================================================================
def max_two(a: float, b: float) -> float:
    """
    Возвращает большее из двух переданных чисел.
    
    Параметры:
        a (float): первое число
        b (float): второе число
    
    Возвращает:
        float: большее значение (или любое из них, если они равны)
    """
    if a >= b:
        return a
    else:
        return b


# =====================================================================
# Основной блок программы
# =====================================================================
def main():
    print("=== ЧАСТЬ 1: ПРОВЕРКА ЧЕТНОСТИ ЧИСЛА ===")
    try:
        raw_number = input("Введите целое число для проверки: ").strip()
        num = int(raw_number)
        
        # Конструкция if/elif/else с тремя логическими исходами:
        # 1. Ноль (особый нейтральный случай четного числа)
        # 2. Положительное/отрицательное четное число
        # 3. Нечетное число
        if num == 0:
            print(f"Число {num} — это ноль (четное число).")
        elif num % 2 == 0:
            print(f"Число {num} — чётное.")
        else:
            print(f"Число {num} — нечётное.")
            
    except ValueError:
        print("Ошибка: введено некорректное значение! Требуется целое число.")

    print("\n=== ЧАСТЬ 2: ЧИСЛА ОТ 1 ДО N, КРАТНЫЕ 3 ===")
    try:
        raw_n = input("Введите целое число N (верхняя граница диапазона): ").strip()
        n = int(raw_n)
        
        if n < 1:
            print(f"Диапазон [1; {n}] пуст. Введите число N >= 1.")
        else:
            # Накапливаем и выводим числа, кратные 3
            multiples_of_three = []
            for i in range(1, n + 1):
                if i % 3 == 0:
                    multiples_of_three.append(i)
            
            if multiples_of_three:
                print(f"Числа от 1 до {n}, кратные 3: {', '.join(map(str, multiples_of_three))}")
            else:
                print(f"В диапазоне от 1 до {n} нет чисел, кратных 3.")
                
    except ValueError:
        print("Ошибка: параметр N должен быть целым числом.")

    print("\n=== ЧАСТЬ 3: РАБОТА С ФУНКЦИЕЙ max_two(a, b) ===")
    # Серия вызовов функции с разными тестовыми аргументами (целые, дробные, равные)
    test_pairs = [
        (15, 42),
        (3.1415, 2.7182),
        (-10, -3),
        (7.5, 7.5),
    ]
    
    print("Демонстрация вызова max_two(a, b) на тестовых наборах:")
    for x, y in test_pairs:
        result = max_two(x, y)
        print(f"max_two({x}, {y}) -> {result}")


if __name__ == "__main__":
    main()
  
